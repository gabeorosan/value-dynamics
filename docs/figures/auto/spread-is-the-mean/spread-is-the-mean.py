def qx(q):
    return PX0 + q * (PX1 - PX0)


def ay(s):
    return AY0 - s / SMAX * (AY0 - ATOP)


def by(share):
    return BY0 - share / SHMAX * (BY0 - BTOP)


def chip_pool(cx, cy, k, n=N_CAND, side=15, gap=4):
    """A whole pool drawn as n little squares, k of them filled."""
    total = n * side + (n - 1) * gap
    x = cx - total / 2.0
    out = []
    for i in range(n):
        fill = INK if i < k else "white"
        out.append(f'<rect x="{x + i * (side + gap):.1f}" y="{cy}" '
                   f'width="{side}" height="{side}" rx="3" fill="{fill}" '
                   f'stroke="{INK}" stroke-width="2"/>')
    return "\n".join(out)


