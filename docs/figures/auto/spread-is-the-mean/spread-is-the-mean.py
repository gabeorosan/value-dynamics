def load():
    if os.path.exists(SUPPLY):
        with open(SUPPLY) as fh:
            d = json.load(fh)
        for k, v in FALLBACK["by_round"]["raw_spread"].items():
            got = d["by_round"]["raw_spread"][k]["mean"]
            if abs(got - v["mean"]) > 1e-9:
                print(f"WARNING: embedded {k} spread {v['mean']} != file {got}")
        return d
    print("NOTE: experiments/spread_supply.json not found; using the "
          "embedded verified copy.")
    return FALLBACK


def sigma(q, n=N_CAND):
    """The identity itself: sample standard deviation of n binary scores."""
    return math.sqrt(n / (n - 1.0)) * math.sqrt(max(q * (1.0 - q), 0.0))


# ---- geometry -----------------------------------------------------------
